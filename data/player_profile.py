VIEW4_OFFSET = {"A": ("B", 96), "B": ("A", 97)}


def to_view4(pos):
    """把 view3 的位置字串（例如 "98B"）換成 track_legend_1064 的編號。"""
    n, side = int(pos[:-1]), pos[-1]
    for ns, (os_, off) in VIEW4_OFFSET.items():
        if os_ == side:
            return f"{n - off}{ns}"
    raise ValueError(pos)

