def to_view4(pos):
    """把 view3 的位置字串（例如 "98B"）換成 view4（track_1077_rock）的編號。"""
    n, side = int(pos[:-1]), pos[-1]
    for ns, (os_, off) in VIEW4_OFFSET.items():
        if os_ == side:
            return f"{n - off}{ns}"
    raise ValueError(pos)


def to_view5(pos):
    """把 view4 的位置字串（例如 "47A"）換成目前視角 view5 的編號。"""
    n, side = int(pos[:-1]), pos[-1]
    return f"{n - VIEW5_OFFSET}{side}"

